import math
#mathをインポートすることで、数学関数を使用できるように
print(math.sin(0))
#math.sin()は、引数の値のサインを返す関数
print(math.cos(0))
#math.cos()は、引数の値のコサインを返す関数 
print(math.tan(0))
#math.tan()は、引数の値のタンジェントを返す関数
print(math.sqrt(4))
#math.sqrt()は、引数の値の平方根を返す関数
print(math.pow(2, 3))
#math.pow()は、引数の値のべき乗を返す関数
print(math.pi)
#math.piは、円周率の値を返す定数
print(math.e)
#math.eは、自然対数の底の値を返す定数